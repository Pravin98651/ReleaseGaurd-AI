"use client";

import React from "react";
import {
  Bot,
  Calculator,
  Eye,
  FlaskConical,
  HelpCircle,
  ShieldCheck,
} from "lucide-react";
import { cn } from "@/lib/utils";

export type EvidenceClass =
  | "VERIFIED"
  | "OBSERVED"
  | "SIMULATED"
  | "AI_INFERRED"
  | "ESTIMATED"
  | "UNKNOWN";

export const EVIDENCE_CLASSES: readonly EvidenceClass[] = [
  "VERIFIED",
  "OBSERVED",
  "SIMULATED",
  "AI_INFERRED",
  "ESTIMATED",
  "UNKNOWN",
] as const;

interface EvidenceMeta {
  label: string;
  shortLabel: string;
  description: string;
  tone: string;
  Icon: React.ComponentType<{ className?: string }>;
}

const EVIDENCE_META: Record<EvidenceClass, EvidenceMeta> = {
  VERIFIED: {
    label: "Verified",
    shortLabel: "Verified",
    description: "Cryptographically or deterministically verified against live source records",
    tone: "border-emerald-500/35 bg-emerald-500/10 text-emerald-300",
    Icon: ShieldCheck,
  },
  OBSERVED: {
    label: "Observed",
    shortLabel: "Observed",
    description: "Directly observed from live runtime telemetry or integration events",
    tone: "border-sky-500/35 bg-sky-500/10 text-sky-300",
    Icon: Eye,
  },
  SIMULATED: {
    label: "Simulated",
    shortLabel: "Simulated",
    description: "Generated by synthetic simulation or replay cohorts",
    tone: "border-amber-500/35 bg-amber-500/10 text-amber-300",
    Icon: FlaskConical,
  },
  AI_INFERRED: {
    label: "AI Inferred",
    shortLabel: "AI Inferred",
    description: "Inferred by LLM analysis; not directly measured",
    tone: "border-indigo-500/35 bg-indigo-500/10 text-indigo-300",
    Icon: Bot,
  },
  ESTIMATED: {
    label: "Estimated",
    shortLabel: "Estimated",
    description: "Derived from heuristic or baseline estimation",
    tone: "border-orange-500/35 bg-orange-500/10 text-orange-300",
    Icon: Calculator,
  },
  UNKNOWN: {
    label: "Unknown",
    shortLabel: "Unknown",
    description: "Evidence provenance unavailable or incomplete",
    tone: "border-slate-700 bg-slate-800/70 text-slate-400",
    Icon: HelpCircle,
  },
};

export function normalizeEvidenceClass(value?: string | null): EvidenceClass {
  if (!value) return "UNKNOWN";
  const upper = value.trim().toUpperCase().replace(/[\s-]+/g, "_");
  if (upper === "VERIFIED" || upper === "VERIFIED_MEASURED") return "VERIFIED";
  if (upper === "OBSERVED") return "OBSERVED";
  if (upper === "SIMULATED") return "SIMULATED";
  if (upper === "AI_INFERRED") return "AI_INFERRED";
  if (upper === "ESTIMATED") return "ESTIMATED";
  return "UNKNOWN";
}

export interface EvidenceBadgeProps {
  evidenceClass?: EvidenceClass | string | null;
  label?: string;
  detail?: string;
  compact?: boolean;
  className?: string;
}

export function EvidenceBadge({
  evidenceClass,
  label,
  detail,
  compact = false,
  className,
}: EvidenceBadgeProps) {
  const normalized = normalizeEvidenceClass(evidenceClass);
  const meta = EVIDENCE_META[normalized];
  const { Icon } = meta;

  return (
    <span
      data-evidence-class={normalized}
      title={detail ?? meta.description}
      className={cn(
        "inline-flex items-center gap-1 rounded-md border font-medium tracking-tight",
        compact ? "px-1.5 py-0.5 text-[10px]" : "px-2 py-0.5 text-[11px]",
        meta.tone,
        className
      )}
    >
      <Icon className={compact ? "h-2.5 w-2.5 shrink-0" : "h-3 w-3 shrink-0"} />
      <span>{label ?? (compact ? meta.shortLabel : meta.label)}</span>
    </span>
  );
}
